function frLesson(id, title, sub, icon, goals, groups, names, lines, notes, quiz) {
    var vocab = [];
    groups.forEach(function (group) {
        group[1].forEach(function (word) {
            vocab.push({ k: id + '-' + vocab.length, t: word[0], pr: word[1], ar: word[2], g: group[0] });
        });
    });
    return {
        id: id,
        level: 'A1',
        icon: icon,
        title: title,
        sub: sub,
        goals: goals,
        vocab: vocab,
        dialog: { names: names, lines: lines.map(function (line) { return { w: line[0], t: line[1], ar: line[2] }; }) },
        notes: notes,
        quiz: quiz.map(function (item) { return { q: item[0], a: item[1], c: item[2] }; })
    };
}

